"""
handlers/join_handler.py

Completes the Add Member workflow. When a user joins a managed channel
(through the single-use invite link generated by add_member_handler, or
by any other means, e.g. an existing public link), Telegram fires a
ChatMemberUpdated event. We catch it here, check whether the chat is one
of our managed channels, and if the new status shows they are now a
member, register them into that channel's Excel sheet automatically.

This does not require - and never attempts - any unsupported "force add"
API call. It only reacts to joins that already happened.
"""

from pyrogram import Client, filters
from pyrogram.enums import ChatMemberStatus
from pyrogram.types import ChatMemberUpdated

from services.log_service import LogService


ACTIVE_STATUSES = {ChatMemberStatus.MEMBER, ChatMemberStatus.ADMINISTRATOR, ChatMemberStatus.OWNER}


def register(app: Client) -> None:

    @app.on_chat_member_updated()
    async def on_member_joined(client: Client, update: ChatMemberUpdated):
        try:
            new_status = update.new_chat_member.status if update.new_chat_member else None
            if new_status not in ACTIVE_STATUSES:
                return

            channels = await client.channel_service.get_all()
            channel = next((c for c in channels if c["chat_id"] == update.chat.id), None)
            if not channel:
                return  # Not a channel this bot manages.

            user = update.new_chat_member.user
            if user is None or user.is_bot:
                return

            full_name = " ".join(filter(None, [user.first_name, user.last_name]))
            added = await client.excel_service.add_member(
                channel_name=channel["name"],
                telegram_id=user.id,
                username=user.username,
                full_name=full_name,
                status="Active",
            )

            await client.excel_service.write_log(
                action="ADD",
                admin="auto-join",
                user=f"@{user.username}" if user.username else str(user.id),
                channel=channel["name"],
                status="registered" if added else "updated",
            )
        except Exception as exc:  # noqa: BLE001 - a broken update must never crash the bot
            log_service: LogService = getattr(client, "log_service", None)
            if log_service:
                log_service.error("on_member_joined failed", exc)
